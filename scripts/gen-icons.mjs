#!/usr/bin/env node
/**
 * Generate `src/lib/iconPaths.ts` — the SVG path data for every Phosphor icon
 * the app uses, read from `@phosphor-icons/core` (a devDependency).
 *
 * Why not `@phosphor-icons/vue`: each of its components bundles all six
 * weights, which put ~110 KB of path data into the first-load vendor chunk for
 * ~40 icons. Here we keep one weight per icon (a few hundred bytes each) and
 * render it through a tiny Vuetify icon set (src/lib/icons.ts).
 *
 * Usage: node scripts/gen-icons.mjs   (re-run after editing ICONS below)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = resolve(root, 'node_modules/@phosphor-icons/core/assets');

/** key in the generated map → [phosphor icon name, weight] */
const ICONS = {
  arrowCounterClockwise: ['arrow-counter-clockwise', 'regular'],
  arrowsClockwiseBold: ['arrows-clockwise', 'bold'],
  caretDown: ['caret-down', 'regular'],
  caretLeft: ['caret-left', 'regular'],
  caretRight: ['caret-right', 'regular'],
  caretUp: ['caret-up', 'regular'],
  check: ['check', 'regular'],
  checkCircle: ['check-circle', 'regular'],
  checkSquare: ['check-square', 'regular'],
  circle: ['circle', 'regular'],
  coffee: ['coffee', 'regular'],
  cube: ['cube', 'regular'],
  dotsSix: ['dots-six', 'regular'],
  downloadSimple: ['download-simple', 'regular'],
  folderOpen: ['folder-open', 'regular'],
  info: ['info', 'regular'],
  magicWand: ['magic-wand', 'regular'],
  magnifyingGlassMinus: ['magnifying-glass-minus', 'regular'],
  minusSquare: ['minus-square', 'regular'],
  moon: ['moon', 'regular'],
  paperclip: ['paperclip', 'regular'],
  pause: ['pause', 'regular'],
  personSimpleWalk: ['person-simple-walk', 'regular'],
  play: ['play', 'regular'],
  radioButton: ['radio-button', 'regular'],
  repeat: ['repeat', 'regular'],
  robot: ['robot', 'regular'],
  skipBack: ['skip-back', 'regular'],
  skipForward: ['skip-forward', 'regular'],
  slidersHorizontal: ['sliders-horizontal', 'regular'],
  square: ['square', 'regular'],
  stop: ['stop', 'regular'],
  sun: ['sun', 'regular'],
  trash: ['trash', 'regular'],
  uploadSimple: ['upload-simple', 'regular'],
  videoCamera: ['video-camera', 'regular'],
  warning: ['warning', 'regular'],
  x: ['x', 'regular'],
  xCircle: ['x-circle', 'regular'],
};

const lines = [];
for (const [key, [name, weight]] of Object.entries(ICONS)) {
  const file = weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`;
  const svg = readFileSync(resolve(assets, weight, file), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0 || /<(circle|rect|line|polyline|polygon)\b/.test(svg)) {
    throw new Error(`${file}: expected path-only SVG`);
  }
  // Several sub-paths of one filled icon concatenate into a single `d`.
  lines.push(`  ${key}: '${paths.join(' ')}',`);
}

const version = JSON.parse(
  readFileSync(resolve(root, 'node_modules/@phosphor-icons/core/package.json'), 'utf8'),
).version;
writeFileSync(
  resolve(root, 'src/lib/iconPaths.ts'),
  `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core@${version} (MIT). Do not edit.
// 256×256 viewBox path data, one weight per icon.
export const PHOSPHOR_PATHS = {
${lines.join('\n')}
} as const;
`,
);
console.log(`wrote src/lib/iconPaths.ts (${Object.keys(ICONS).length} icons)`);
